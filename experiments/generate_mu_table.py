"""Regenerate the native finite-source Chebyshev coefficients from disk and boundary quadrature.

Run from the checkout with an existing project-local build directory as argument, optionally followed by "uniform".
Tables store radius-scaled magnifications. Each patch uses Gauss-Chebyshev nodes, so neither
the point-source singularity nor exact contact enters the generator.
"""
import subprocess
import sys
from pathlib import Path

import numpy as np
from scipy.fft import dct

root = Path(__file__).resolve().parents[1]
include = root / "src/singlelensfitter/cpp"
build = Path(sys.argv[1]).resolve()
uniform = sys.argv[2:] == ["uniform"]
basis = "uniform" if uniform else "mu"
source = build / f"sample_{basis}.cpp"
binary = build / f"sample_{basis}"
kernel = ("limb_sum<false,320>(z,rho)" if uniform else
          "near_mu_moment<false,96>(rho*z,rho)")
source.write_text('''#include "mu_quadrature.hpp"
#include <cstdio>
int main() {
    double rho, z;
    while (std::scanf("%lf %lf", &rho, &z) == 2)
        std::printf("%.17g\\n", rho * singlelensfitter::KERNEL.value);
}
'''.replace('KERNEL', kernel))
subprocess.run(["c++", "-std=c++17", "-O3", "-I", str(include), str(source),
                "-o", str(binary)], check=True)
order = 14
radii = [0, .0625, .125, .25, .5, 1, 1.5, 2, 4, 8, 16, 32]
if uniform:
    radii = [0., .5, 1., 1.5, 2.]
nodes = np.cos(np.pi * (np.arange(order) + .5) / order)
samples = []
for lo, hi in zip(radii, radii[1:]):
    for patch in range(17 if uniform else 8):
        for rho in lo + (hi-lo)*(nodes+1)/2:
            if uniform:
                if patch < 6:
                    exponent = -16 + 4*(patch%3) + 2*(nodes+1)
                else:
                    # Half-octaves from gap 1/16 up to the center (inside)
                    # or the end of the limb blending interval (outside).
                    index = patch-6 if patch < 14 else patch-14
                    exponent = -4 + index*.5 + (nodes+1)*.25
                inside = patch < 3 or 6 <= patch < 14
                z = (-1 if inside else 1)*np.exp2(exponent)
            else:
                y = (patch if patch < 2 else patch-2)*.5 + (nodes+1)/4
                z = np.sqrt(y) if patch < 2 else 1+y*y
            samples.extend(f"{rho:.17g} {v:.17g}\n" for v in z)
result = subprocess.run([str(binary)], input="".join(samples), capture_output=True,
                        text=True, check=True)
values = np.fromstring(result.stdout, sep=" ").reshape(-1, order, order)
coeff = dct(dct(values, axis=1), axis=2)/order**2
coeff[:, 0, :] /= 2
coeff[:, :, 0] /= 2
with (include / f"{basis}_table_data.hpp").open("w") as out:
    out.write("// Generated by experiments/generate_mu_table.py\n#pragma once\n")
    out.write(f"namespace singlelensfitter::{basis}_table {{\n")
    out.write("inline constexpr double radii[] = {" + ", ".join(map(str,radii)) + "};\n")
    out.write(f"inline constexpr int order = {order};\n")
    out.write("inline constexpr double coefficients[][order][order] = {\n")
    for matrix in coeff:
        out.write("{\n")
        for row in matrix:
            out.write("    {" + ", ".join(format(x, ".17g") for x in row) + "},\n")
        out.write("},\n")
    out.write("};\n}\n")
